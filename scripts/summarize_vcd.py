"""Summarize an existing top-level trace; does not compile or simulate RTL."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'results/waveforms/tiny_npu_top.vcd'


def snapshot_at_done(path):
    scopes, identifiers, values = [], {}, {}
    body, time = False, 0
    for line in path.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if not body:
            parts = line.split()
            if line.startswith('$scope '):
                scopes.append(parts[2])
            elif line.startswith('$upscope'):
                scopes.pop()
            elif line.startswith('$var '):
                identifiers['.'.join(scopes + [parts[4]])] = parts[3]
            elif line.startswith('$enddefinitions'):
                body = True
            continue
        if line.startswith('#'):
            if values.get(identifiers['tb_tiny_npu_top.done']) == '1':
                return time, values.copy(), identifiers
            time = int(line[1:])
        elif line.startswith(('b', 'B')):
            bits, identifier = line[1:].split()
            values[identifier] = bits
        elif line and line[0] in '01xXzZ':
            values[line[1:]] = line[0].lower()
    if values.get(identifiers['tb_tiny_npu_top.done']) == '1':
        return time, values, identifiers
    raise ValueError('No snapshot with done = 1 was found')


def main():
    time, values, ids = snapshot_at_done(SOURCE)
    packed = int(values[ids['tb_tiny_npu_top.c_flat']], 2)
    errors = int(values[ids['tb_tiny_npu_top.errors']], 2)
    observed = []
    for r in range(4):
        row = []
        for c in range(4):
            word = (packed >> (32 * (4*r+c))) & 0xffffffff
            row.append(word if word < (1 << 31) else word - (1 << 32))
        observed.append(row)
    a = [[4*r+c+1 for c in range(4)] for r in range(4)]
    b = [[1, 0, 2, 0], [0, 1, 0, 2], [1, 0, 1, 0], [0, 1, 0, 1]]
    expected = [[sum(a[r][k]*b[k][c] for k in range(4)) for c in range(4)] for r in range(4)]
    for name, matrix in [('a_matrix', a), ('b_matrix', b)]:
        expected_input = sum((matrix[r][c] & 255) << (8*(4*r+c)) for r in range(4) for c in range(4))
        if int(values[ids['tb_tiny_npu_top.' + name]], 2) != expected_input:
            raise ValueError('Archived input differs from the documented example: ' + name)
    if observed != expected or errors != 0:
        raise ValueError('Archived results differ from the documented example')
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    rows = '\n'.join('| ' + str(r) + ' | ' + ' | '.join(map(str, observed[r])) + ' |' for r in range(4))
    report = f'''# Results extracted from the existing top-level VCD

Source: [tiny_npu_top.vcd](waveforms/tiny_npu_top.vcd), generated by an earlier Icarus Verilog run.

SHA-256: `{digest}`

At the first settled timestamp with `done = 1`, **{time} ps ({time/1000:g} ns)**, the saved output is:

| Row | Column 0 | Column 1 | Column 2 | Column 3 |
|---|---|---|---|---|
{rows}

All 16 extracted elements match `A × B` for the directed example in the README. The input ports in this snapshot also match that example. The saved testbench `errors` value is **{errors}**.

This report is generated by `python scripts/summarize_vcd.py` from an existing trace. It is not a new simulation, a captured PASS console log, or proof of exhaustive test coverage. The archived run has no recorded source commit association.
'''
    (ROOT / 'results/top_waveform_summary.md').write_text(report, encoding='utf-8')
    print('Archived trace: 16/16 outputs match; errors=0; no simulation run.')


if __name__ == '__main__':
    main()
